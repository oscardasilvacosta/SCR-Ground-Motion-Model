# Full-database fit; no resampling, new search, or scenario-based fitting.
script <- sub('^--file=','',grep('^--file=',commandArgs(FALSE),value=TRUE)[1])
source(file.path(dirname(normalizePath(script)),'common.R'))
args <- commandArgs(TRUE)
if(length(args)!=2L) stop('Usage: Rscript R/03_train_final.R PRIVATE_training.csv NEW_output_directory')
d <- read_training(args[1]);out <- new_output(args[2]);model <- fit_model(d,seed=123L)
save_fit(model,out,'XGB2.9G_FULL_DB');p <- as.numeric(predict(model,newdata=d))
check <- readRDS(file.path(out,'XGB2.9G_FULL_DB.rds'))
stopifnot(max(abs(as.numeric(predict(check,d))-p))<1e-8)
write.csv(score(d[[target]],p),file.path(out,'IN_SAMPLE_metrics_not_validation.csv'),row.names=FALSE)
cat('Saved FULL_DB model. In-sample scores are not generalization estimates.\n')
