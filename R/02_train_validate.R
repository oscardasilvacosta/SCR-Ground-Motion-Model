# Fixed settings on the adopted recording-level partition, not a new grid search.
script <- sub('^--file=','',grep('^--file=',commandArgs(FALSE),value=TRUE)[1])
source(file.path(dirname(normalizePath(script)),'common.R'))
args <- commandArgs(TRUE)
if(length(args)!=2L) stop('Usage: Rscript R/02_train_validate.R PRIVATE_training.csv NEW_output_directory')
d <- read_training(args[1]);split <- primary_partition();out <- new_output(args[2])
model <- fit_model(d[split$train,],seed=123L,evaluation_final_seed=365209L)
p <- as.numeric(predict(model,newdata=d[split$test,]));metrics <- score(d[[target]][split$test],p)
write.csv(metrics,file.path(out,'SCR_validation_metrics.csv'),row.names=FALSE)
write.csv(data.frame(record_id=d$record_id[split$test],observed_pctg=d[[target]][split$test],predicted_pctg=p),
  file.path(out,'SCR_validation_predictions.csv'),row.names=FALSE)
save_fit(model,out,'XGB2.9G_EVALUATION')
check <- readRDS(file.path(out,'XGB2.9G_EVALUATION.rds'))
stopifnot(max(abs(as.numeric(predict(check,d[split$test,]))-p))<1e-8)
print(metrics)
cat('Reused SCR development-validation partition: NOT event-disjoint or an untouched test.\n')
